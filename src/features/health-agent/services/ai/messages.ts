/**
 * CareLink-AI — multilingual user-facing safety copy (Phase 2 §2.2 rule 6, Phase 8 §8.4).
 *
 * Every SAFETY-critical string (emergency banner, emergency instructions,
 * medication consultation notice, uncertainty notices) must appear in the
 * language the user is actually using. These are DETERMINISTIC strings — not
 * model output — so they are available even when the AI provider is down.
 *
 * A missing translation falls back to English rather than showing a broken or
 * machine-guessed string. Each entry is reviewed copy, not a raw translation of
 * a fixed English sentence.
 *
 * Pure data + pure lookup functions — no I/O, fully unit-testable.
 */

import type { AgentLanguage } from '../../types';

export interface LocalizedText {
  en: string;
  [language: string]: string | undefined;
}

/** Pick the string for the requested language, falling back to English. */
export function localized(text: LocalizedText, language: AgentLanguage): string {
  return text[language] ?? text.en;
}

